import base64, io, sys, openpyxl
wb = openpyxl.load_workbook(io.BytesIO(base64.b64decode(open('teste/planilha.xlsx.b64').read())))
ws = wb.create_sheet('Tabela de preços')
ws.append(['Markup do mês', 1.43])
ws.append([])
ws.append(['Código de barras', 'Produto', 'Preço de custo (R$)', 'Preço de venda (R$)'])
ws.append(['7891234567895', 'ARTICULAÇÃO AXIAL HIDRÁULICA UNO/FIORINO APÓS 93', 47.25, 67.57])
ws.append(['7890000000017', 'AMORTECEDOR DIANTEIRO GP30120 COFAP', 300, 429])
ws.append([None, 'Filtro de Combustível FCFB001', None, 35])
ws.append(['7890000000024', 'Pneu 175/70 R13 Teste', 200, 286])
ws.append([None, 'Filtro de Combustível FS04/7 VOX', None, None])
out = io.BytesIO(); wb.save(out)
open('teste/planilha-precos.xlsx.b64', 'w').write(base64.b64encode(out.getvalue()).decode())
